def area(a, b):
    """Возвращает площадь прямоугольника со сторонами a и b."""
    if a < 0 or b < 0:
        raise ValueError("Стороны должны быть неотрицательными")
    return a * b


def perimeter(a, b):
    """Возвращает периметр прямоугольника со сторонами a и b."""
    if a < 0 or b < 0:
        raise ValueError("Стороны должны быть неотрицательными")
    return 2 * (a + b)
