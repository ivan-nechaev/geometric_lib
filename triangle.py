def area(a, h):
    """Возвращает площадь треугольника по основанию a и высоте h."""
    if a < 0 or h < 0:
        raise ValueError("Основание и высота должны быть неотрицательными")
    return a * h / 2


def perimeter(a, b, c):
    """Возвращает сумму сторон треугольника. Допускает вырожденный случай."""
    if a < 0 or b < 0 or c < 0:
        raise ValueError("Стороны должны быть неотрицательными")
    if a + b < c or a + c < b or b + c < a:
        raise ValueError("Сумма двух сторон должна быть не меньше третьей")
    return a + b + c
